"""Build a Wiki Trails test dataset from real Wikispeedia human click paths.

Source: Wikispeedia (West & Leskovec, SNAP, Stanford), paths_finished.tsv.
In a path, '<' means the player pressed back; the next article is then clicked
from the page they went back to, which is exactly Wiki Trails' branch model.
"""
import sys, json, random, datetime, urllib.parse as up, collections

src, out, target_clicks = sys.argv[1], sys.argv[2], int(sys.argv[3])
spread_days = int(sys.argv[4]) if len(sys.argv) > 4 else 0  # >0: re-time trails evenly over the last N days
seed = int(sys.argv[5]) if len(sys.argv) > 5 else 42
rnd = random.Random(seed)
title = lambda s: up.unquote(s).replace('_', ' ')

rows = []
for line in open(src, encoding='utf8'):
    if line.startswith('#') or not line.strip():
        continue
    ip, ts, dur, path, rating = line.rstrip('\n').split('\t')
    rows.append((int(ts), path.split(';'), int(dur)))

by_game = collections.defaultdict(list)
for r in rows:
    ts, p, _ = r
    by_game[(p[0], p[-1])].append(r)

def clicks(p):
    return sum(1 for x in p[1:] if x != '<')

# Mix: lots of the popular games (shared routes get thick), plus random one-off games.
popular = [('Brain', 'Telephone'), ('Asteroid', 'Viking'), ('Theatre', 'Zebra'), ('Pyramid', 'Bean')]
weights = (0.24, 0.20, 0.18, 0.14) if target_clicks <= 5000 else (0.07, 0.06, 0.05, 0.04)  # big sets: more diverse, like real long-term use
quota = {g: int(target_clicks * w) for g, w in zip(popular, weights)}
chosen = []
for g in popular:
    pool = [r for r in by_game[g] if 3 <= clicks(r[1]) <= 14]
    rnd.shuffle(pool); n = 0
    for r in pool:
        if n >= quota[g]: break
        chosen.append(r); n += clicks(r[1])
rest = [r for r in rows if (r[1][0], r[1][-1]) not in popular and 3 <= clicks(r[1]) <= 12]
rnd.shuffle(rest)
total = sum(clicks(r[1]) for r in chosen)
for r in rest:
    if total >= target_clicks: break
    chosen.append(r); total += clicks(r[1])
chosen.sort(key=lambda r: r[0])

import time as _time
if spread_days:
    now = int(_time.time()); span = spread_days * 86400
    # keep the original order and rhythm, squeeze it into the last N days, browsing in the daytime
    t0, t1 = chosen[0][0], chosen[-1][0]
    chosen = [(now - span + int((ts - t0) / max(1, t1 - t0) * span), p, d) for ts, p, d in chosen]
    chosen = [((ts // 86400) * 86400 + 9 * 3600 + (ts % 50400), p, d) for ts, p, d in chosen]
import math
t_first, t_last = chosen[0][0], chosen[-1][0]
def dwell(ts):
    """Seconds spent on a page, simulated (game players race, so the real timings are all quick).
    About a third of pages are read for minutes, the rest skimmed; the share drifts slowly over time."""
    f = (ts - t_first) / max(1, t_last - t_first)
    p_read = 0.33 + 0.12 * math.sin(f * math.pi * 5)
    return int(rnd.uniform(90, 540)) if rnd.random() < p_read else int(rnd.uniform(6, 45))
trails = []
for i, (ts, p, dur) in enumerate(chosen):
    visits, stack, t = [], [], ts
    for j, tok in enumerate(p):
        if tok == '<':
            if len(stack) > 1: stack.pop()
            t += 3  # going back takes a moment
            continue
        vid = f'{i:x}-{j:x}'
        visits.append({'id': vid, 'article': title(tok), 'parent': stack[-1] if stack else None, 't': t * 1000})
        stack.append(vid)
        t += dwell(ts)
    trails.append({
        'id': f't{i:04x}',
        'name': f'{title(p[0])} → {title(p[-1])}',
        'created': datetime.datetime.fromtimestamp(ts, datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%S.000Z'),
        'visits': visits,
    })

json.dump({'version': 2, 'lang': 'en', 'source': 'Wikispeedia human paths (SNAP, Stanford), CC BY-SA', 'trails': trails},
          open(out, 'w', encoding='utf8'), ensure_ascii=False, separators=(',', ':'))
js_out = out[:-5] + '.js' if out.endswith('.json') else out + '.js'
import os
stem = os.path.basename(out)[:-5]
open(js_out, 'w', encoding='utf8').write(f'// Generated by scripts/build_test_data.py; loaded as a script so it works from file://\n(window.WIKI_TRAILS_DATA = window.WIKI_TRAILS_DATA || {{}})[{json.dumps(stem)}] = ' + open(out, encoding='utf8').read() + ';\n')
arts = {v['article'] for t in trails for v in t['visits']}
backs = sum(r[1].count('<') for r in chosen)
print(f'{len(trails)} trails, {total} clicks, {backs} back-steps, {len(arts)} articles')
